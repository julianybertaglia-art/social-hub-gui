const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE||'/usr/bin/chromium',args:['--no-sandbox']});
 const errors=[];
 const page=await browser.newPage({viewport:{width:1280,height:850}});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:3813/crm/vital',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Atendimentos',exact:true}).last().click();
 await page.getByRole('button',{name:'Cliente de exemplo'}).click();
 await page.getByText('Olá! Como posso ajudar você?').waitFor();
 await page.getByRole('button',{name:'Loja Nuvemshop'}).click();
 await page.getByText('Cliente da loja de teste',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Pedidos',exact:true}).click();
 await page.getByText('Pedido 111',{exact:false}).waitFor();
 await page.getByRole('button',{name:'Atendimentos',exact:true}).last().click();
 let board=page.locator('[data-crm-board]');
 let wide=await board.boundingBox();
 let history=await page.getByLabel('Histórico de mensagens').boundingBox();
 assert.ok(history.height>=300,`desktop message area too short: ${history.height}`);
 assert.equal(await page.getByRole('button',{name:'Abrir menu lateral'}).getAttribute('aria-expanded'),'false');
 await page.screenshot({path:'desktop-recolhido.png'});
 await page.getByRole('button',{name:'Abrir menu lateral'}).click();
 let narrow=await board.boundingBox();
 assert.ok(wide.width-narrow.width>=240,`expected larger board: ${wide.width} vs ${narrow.width}`);
 assert.equal(await page.getByRole('button',{name:'Recolher menu lateral'}).getAttribute('aria-expanded'),'true');
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.getByRole('button',{name:'Recolher menu lateral'}).getAttribute('aria-expanded'),'true');
 await page.getByRole('button',{name:'Recolher menu lateral'}).click();
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.getByRole('button',{name:'Abrir menu lateral'}).getAttribute('aria-expanded'),'false');
 const mobile=await browser.newPage({viewport:{width:390,height:844}});
 mobile.on('pageerror',e=>errors.push(e.message));
 await mobile.goto('http://127.0.0.1:3813/crm/vital',{waitUntil:'networkidle'});
 await mobile.getByRole('button',{name:'Atendimentos',exact:true}).last().click();
 const mobileTabs=mobile.getByRole('navigation',{name:'Navegação do CRM'});
 const firstTab=await mobileTabs.getByRole('button',{name:'Dashboard'}).boundingBox();
 const lastTab=await mobileTabs.getByRole('button',{name:'Loja Nuvemshop'}).boundingBox();
 assert.ok(Math.abs(firstTab.y-lastTab.y)<3,'mobile CRM tabs should share one row');
 await mobile.getByRole('button',{name:'Cliente de exemplo'}).click();
 await mobile.getByText('Olá! Como posso ajudar você?').waitFor();
 let mobileHistory=await mobile.getByLabel('Histórico de mensagens').boundingBox();
 assert.ok(mobileHistory.height>=300,`mobile message area too short: ${mobileHistory.height}`);
 assert.equal(await mobile.getByRole('button',{name:'Cliente de exemplo'}).isVisible(),false);
 await mobile.screenshot({path:'mobile-conversa.png'});
 await mobile.getByRole('button',{name:'Fechar conversa'}).click();
 assert.equal(await mobile.getByRole('button',{name:'Cliente de exemplo'}).isVisible(),true);
 await mobile.getByRole('button',{name:'Abrir menu',exact:true}).click();
 assert.equal(await mobile.getByRole('navigation',{name:'Áreas da TidePlace'}).isVisible(),true);
 const gui=await browser.newPage({viewport:{width:1280,height:850}});
 gui.on('pageerror',e=>errors.push(e.message));
 await gui.goto('http://127.0.0.1:3813/crm/vital?role=gui',{waitUntil:'networkidle'});
 await gui.getByText('Cliente da loja de teste',{exact:true}).waitFor();
 assert.equal(await gui.getByRole('button',{name:'Atendimentos',exact:true}).count(),0);
 assert.equal(await gui.getByRole('button',{name:'Dashboard',exact:true}).count(),0);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({desktopWidthCollapsed:Math.round(wide.width),desktopWidthExpanded:Math.round(narrow.width),extraWidth:Math.round(wide.width-narrow.width),desktopToggle:'ok',persistence:'ok',mobileChatAndMenu:'ok',storeOwner:'ok',storeOnlyGui:'ok',browserErrors:errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
